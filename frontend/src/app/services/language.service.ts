    translate(key: string, params: any = null): string {
        const lang = this.currentLang();
        const keys = key.split('.');
        let result = this.translations[lang] || this.translations['en'];

        for (const k of keys) {
            if (result && result[k]) {
                result = result[k];
            } else {
                // Fallback to English if key missing in current language
                let fallback = this.translations['en'];
                let foundFallback = true;
                for (const fk of keys) {
                    if (fallback && fallback[fk]) {
                        fallback = fallback[fk];
                    } else {
                        foundFallback = false;
                        break;
                    }
                }
                result = foundFallback ? fallback : key;
                break;
            }
        }

        if (typeof result === 'string' && params) {
            Object.keys(params).forEach(p => {
                const placeholder = `{{${p}}}`;
                result = (result as string).replace(new RegExp(placeholder, 'g'), params[p]);
            });
        }

        return result;
    }

    setLanguage(code: string) {
        if (this.translations[code] || this.supportedLanguages.find(l => l.code === code)) {
            this.currentLang.set(code);
            localStorage.setItem('lang', code);
            // Some languages are RTL
            this.updateLayoutDirection(code);
        }
    }

    getCurrentLanguage() {
        return this.currentLang();
    }

    private updateLayoutDirection(code: string) {
        const isRtl = code === 'ar' || code === 'fa';
        document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
        document.documentElement.lang = code;
    }

    // Initialize layout direction on service creation
    constructor() {
        this.updateLayoutDirection(this.currentLang());
    }
